import fs from "node:fs";
import path from "node:path";

const rootDir = process.cwd();
const actorsDir = path.join(rootDir, "public", "actors");
const outputFile = path.join(rootDir, "src", "constants", "spritesheets.ts");

function isDirectory(targetPath) {
  return fs.existsSync(targetPath) && fs.statSync(targetPath).isDirectory();
}

function fileExists(targetPath) {
  return fs.existsSync(targetPath) && fs.statSync(targetPath).isFile();
}

function getDirectories(sourcePath) {
  if (!isDirectory(sourcePath)) return [];

  return fs
    .readdirSync(sourcePath, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort((a, b) => a.localeCompare(b));
}

function buildSpritesheetsMap() {
  const result = {};
  const actors = getDirectories(actorsDir);

  for (const actor of actors) {
    const actorDir = path.join(actorsDir, actor);
    const animations = getDirectories(actorDir);

    const actorAnimations = {};

    for (const animation of animations) {
      const animationDir = path.join(actorDir, animation);

      const imagePath = path.join(animationDir, "spritesheet.png");
      const atlasPath = path.join(animationDir, "spritesheet.json");

      if (!fileExists(imagePath) || !fileExists(atlasPath)) {
        continue;
      }

      actorAnimations[animation] = {
        key: `${actor}-${animation}`,
        image: `/actors/${actor}/${animation}/spritesheet.png`,
        atlas: `/actors/${actor}/${animation}/spritesheet.json`,
      };
    }

    if (Object.keys(actorAnimations).length > 0) {
      result[actor] = actorAnimations;
    }
  }

  return result;
}

function toTsObject(value, indentLevel = 0) {
  const indent = "  ".repeat(indentLevel);
  const nextIndent = "  ".repeat(indentLevel + 1);

  if (typeof value === "string") {
    return `'${value}'`;
  }

  if (value && typeof value === "object" && !Array.isArray(value)) {
    const entries = Object.entries(value);

    if (entries.length === 0) {
      return "{}";
    }

    const lines = entries.map(([key, val]) => {
      const safeKey = /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(key) ? key : `'${key}'`;
      return `${nextIndent}${safeKey}: ${toTsObject(val, indentLevel + 1)}`;
    });

    return `{\n${lines.join(",\n")}\n${indent}}`;
  }

  return JSON.stringify(value);
}

function generateFileContent(spritesheetsMap) {
  const objectAsTs = toTsObject(spritesheetsMap);

  return `// Auto-generated by scripts/spritesheet/update-spritesheets-constants.mjs
// Do not edit manually.

export type SpritesheetEntry = {
  key: string;
  image: string;
  atlas: string;
};

export const SPRITESHEETS = ${objectAsTs} as const;

export type SpriteActor = keyof typeof SPRITESHEETS;

export type ActorSpritesheets<TActor extends SpriteActor> =
  (typeof SPRITESHEETS)[TActor];

export type SpriteAnimation<TActor extends SpriteActor> =
  keyof ActorSpritesheets<TActor>;
`;
}

function main() {
  const spritesheetsMap = buildSpritesheetsMap();
  const content = generateFileContent(spritesheetsMap);

  fs.mkdirSync(path.dirname(outputFile), { recursive: true });
  fs.writeFileSync(outputFile, content, "utf-8");

  console.log(`Updated spritesheets constants: ${outputFile}`);
}

main();
